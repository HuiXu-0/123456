/** 按当前知识点取导学脚本：核心点用精修引导链，体系点用 kpName 锚定的通用引导序列。 */
export function socraticScriptFor(kpId: string, kpName: string, description?: string): SocraticScript {
  const curated = CURATED[kpId]
  if (curated) return curated
  const hint = description ? `（提示：${description.replace(/。$/, '')}）` : ''
  return {
    opening: `我是你的导学助手 🦉。学习「${kpName}」时，我不会直接给答案，而是用提问引导你思考。先问你：你觉得「${kpName}」是为了解决什么问题而出现的？${hint}`,
    sequence: [
      `很好，方向对了。接着想：「${kpName}」是靠什么核心机制或思路做到这一点的？试着用自己的话概括它「怎么工作」。`,
      `不错！再换个角度检验：如果不用「${kpName}」，只用你之前学过的方法去解决同样的问题，会卡在哪里？这恰恰说明它的关键优势是什么？`,
      `已经很接近本质了。最后一问：你能举一个「${kpName}」的实际应用场景，说说它在其中具体解决了什么问题吗？`,
      `👏 很棒！你已经沿着「动机 → 机制 → 优势 → 应用」把「${kpName}」完整想了一遍。建议回到讲义或图解，把刚才没说准的细节补齐，随时再来找我过一遍。`,
    ],
    fallback: `我们已经把「${kpName}」的主线走完了——还有哪个环节你觉得没想通？指出来，我再帮你拆一拆；也可以点下方「即时辅导」生成针对性资源。`,
    chips: ['它要解决的问题是…', '它的核心思路是…', '它的典型应用是…', '我还没什么头绪'],
  }
}
